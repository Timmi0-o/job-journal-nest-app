function buildJobVariants(): SeedJobVariant[] {
  const variants: SeedJobVariant[] = [];

  for (let index = 0; index < 150; index += 1) {
    const baseName = JOB_VARIANT_NAMES[index % JOB_VARIANT_NAMES.length];
    const suffix =
      index >= JOB_VARIANT_NAMES.length
        ? ` (участок ${Math.floor(index / JOB_VARIANT_NAMES.length) + 1})`
        : '';

    variants.push({
      id: seedUuid(30000000, index + 1),
      name: `${baseName}${suffix}`,
    });
  }

  return variants;
}

export const JOB_VARIANTS_SEED = buildJobVariants();
