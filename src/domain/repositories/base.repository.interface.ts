/**
 * Базовый интерфейс для всех репозиториев
 * Определяет методы для управления транзакционным контекстом
 */
export interface IBaseRepository {
  /**
   * Установить транзакционный клиент для выполнения операций в транзакции
   * Этот метод используется TransactionService для управления транзакциями
   * @param client - Транзакционный клиент БД (или null для сброса)
   */
  setTransactionClient(client: unknown): void;
}
